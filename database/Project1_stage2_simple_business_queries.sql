#Task 5: Sales by Category Display: Category ID, Category name, Total quantity sold, Total sales
Requirements: Join all relevant tables. Include only Completed orders. Use aggregation and GROUP BY. Sort by total sales descending.
SELECT c.category_id, c.category_name, SUM(oi.quantity) AS total_quantity_sold, SUM(oi.quantity * oi.unit_price) AS total_sales
FROM categories c
JOIN products p
ON p.category_id = c.category_id
JOIN order_items oi
ON oi.product_id = p.product_id
JOIN orders o
ON o.order_id = oi.order_id
WHERE o.order_status = 'Completed'
GROUP BY c.category_id, c.category_name
ORDER BY total_sales DESC

#Task 6: Sales by Customer Display: Customer ID, Customer name, Total orders, Total quantity purchased, Total spending
Requirements: Include only Completed orders. Use COUNT(DISTINCT order_id). Use SUM(quantity * unit_price). Sort by total spending descending.
SELECT c.customer_id, c.customer_name, COUNT(DISTINCT o.order_id) AS total_orders, SUM(oi.quantity) AS total_quantity_purchased, SUM(oi.quantity * oi.unit_price) AS total_spending
FROM customers c
JOIN orders o
ON o.customer_id = c.customer_id
JOIN order_items oi
ON oi.order_id = o.order_id
WHERE o.order_status = 'Completed'
GROUP BY c.customer_id, c.customer_name
ORDER BY total_spending DESC

#Task 7: Find Repeat Customers Find customers who have placed at least 2 orders. Display: Customer ID, Customer name, Number of orders
Requirements: Use GROUP BY. Use HAVING. Count distinct orders. Consider Completed orders only.
SELECT c.customer_id, c.customer_name, COUNT(DISTINCT o.order_id) AS total_orders
FROM customers c
JOIN orders o
ON o.customer_id = c.customer_id
WHERE o.order_status = 'Completed'
GROUP BY c.customer_id, c.customer_name
HAVING COUNT(DISTINCT o.order_id) >= 2

#Task 8: Products Never Ordered Find products that have never appeared in any order. Display: Product ID, Product name, Category ID
Requirements: Use LEFT JOIN or NOT EXISTS. Do not count products with zero quantity as ordered unless the order item exists. Return products with no matching order items.
SELECT p.product_id, p.product_name, p.category_id
FROM products p
LEFT JOIN order_items oi
ON oi.product_id = p.product_id
WHERE oi.product_id IS NULL

#Task 9: Compare Order Totals by Status Calculate total order value for each order status. Display: Order status, Number of orders, Total order value
Requirements: Include all statuses: Completed, Shipped, Pending, and Cancelled. Use GROUP BY. Calculate order value using quantity × unit_price. Sort by total order value descending.
SELECT o.order_status, COUNT(DISTINCT o.order_id) AS total_orders, SUM(oi.quantity * oi.unit_price) AS total_order_value
FROM orders o
JOIN order_items oi
ON oi.order_id = o.order_id
GROUP BY o.order_status
ORDER BY total_order_value DESC

#Task 10: Business Summary Challenge Create a single query that displays: Total completed orders, Total completed quantity sold, Total completed revenue, Average completed order value
Requirements: Use joins and aggregation. Use CASE if needed. Ensure the average is calculated per order, not per order item.
SELECT COUNT(DISTINCT o.order_id) AS total_completed_orders, SUM(oi.quantity) AS total_completed_quantity_sold, SUM(oi.quantity * oi.unit_price) AS total_completed_revenue,
SUM(oi.quantity * oi.unit_price) / COUNT(DISTINCT o.order_id) AS average_completed_total_value
FROM orders o
JOIN order_items oi
ON oi.order_id = o.order_id
WHERE o.order_status = 'Completed'

