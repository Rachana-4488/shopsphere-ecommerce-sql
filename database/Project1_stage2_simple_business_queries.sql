#Task 1: List Customers and Their Orders Display: Customer ID, Customer name, Order ID, Order date, Order status, Payment method 
Use JOIN Include customers who have no orders (if any).
SELECT c.customer_id, c.customer_name, o.order_id, o.order_date, o.order_status, o.payment_method
FROM Customers c
LEFT JOIN Orders o
ON c.customer_id = o.customer_id

#Task 2: Calculate Order Value Calculate the total value of each order. Display: Order ID, Total quantity, Order value
Formula: Order Value = quantity × unit_price
Requirements: Use SUM() Use GROUP BY. Round the order value to 2 decimal places.
Method 1:
SELECT distinct order_id, SUM(quantity) OVER(PARTITION BY order_id) AS total_quantity, SUM(quantity * unit_price) OVER(PARTITION BY order_id) AS order_value
FROM order_items
Method 2:
SELECT order_id, SUM(quantity) AS total_quantity, SUM(quantity * unit_price) AS order_value
FROM order_items
GROUP BY order_id

#Task 3: Calculate the total revenue generated by ShopSphere. Display: Total revenue
Requirements: Join ORDERS and ORDER_ITEMS. Consider only orders with status Completed. Use SUM(quantity * unit_price).
Business concept: Revenue should be calculated according to the defined order-status rule.
SELECT SUM(oi.quantity * oi.unit_price) AS total_revenue
FROM order_items oi
JOIN orders o
ON o.order_id = oi.order_id
WHERE o.order_status = 'Completed'

#Task 4: Quantity Sold and Sales by Product Display: Product ID, Product name, Total quantity sold, Total sales
Requirements: Join PRODUCTS, ORDER_ITEMS, and ORDERS. Consider only Completed orders. Use SUM() and GROUP BY. Sort by total sales descending.
Method 1:
SELECT distinct p.product_id, p.product_name, SUM(oi.quantity) OVER(PARTITION BY p.product_id) AS total_quantity_sold, oi.unit_price,
SUM(oi.unit_price * oi.quantity) OVER(PARTITION BY p.product_id) AS total_sales
FROM order_items oi
JOIN products p
ON p.product_id = oi.product_id
JOIN orders o
ON o.order_id = oi.order_id
WHERE o.order_status = 'Completed'
ORDER BY total_sales DESC
